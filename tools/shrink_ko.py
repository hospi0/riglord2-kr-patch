# 종결 뒤에 올 수 있는 것 = 문장 끝 / 개행 / 제어토큰 / 문장부호 / **공백**
# ★공백을 빼먹으면 `～기술입니다 대공공격이～` 처럼 **문장 중간의 종결**을 놓친다.
#   도움말은 한 문자열에 두세 문장이 이어 붙는 일이 흔하다.
TAIL = r'(?=$|\n| |　|%[A-Za-z][0-9]*|[！？，・．」』:～])'

# ㅂ니다 -> ㄴ다 (받침 ㅂ(17) -> ㄴ(4))
JONG_P, JONG_N, JONG_M = 17, 4, 16   # ㅂ / ㄴ / ㅁ

# 「하다」가 형용사인 한자어 — `가능한다`(✗) 가 아니라 `가능하다`(○)
ADJ = ('가능', '필요', '유효', '동일', '비슷', '강력', '중요', '안전', '편리',
       '다양', '특이', '적절', '충분', '유리', '불리', '용이', '희귀')

# 「습니다」 앞 글자가 형용사·존재사면 `-다`, 동사면 `-는다`
ADJ_STEM = set('있없좋많같싶쉽렵높낮크작길짧빠느강약')


def _jamo(ch):
    if not ('가' <= ch <= '힣'):
        return None
    c = ord(ch) - 0xAC00
    return c // 588, (c % 588) // 28, c % 28


def _compose(cho, jung, jong):
    return chr(0xAC00 + cho * 588 + jung * 28 + jong)


def apply_help_style2(t):
    """위 ③ 의 정규식이 헷갈리지 않게 갈래를 나눈 판."""
    log = []
    # ① 「～입니다」 삭제
    def f1(m):
        log.append('입니다 -> (삭제)')
        return ''
    t = re.sub(r'입니다' + TAIL, f1, t)
    # ② 형용사 하다
    for a in ADJ:
        def f2(m, a=a):
            log.append(a + '합니다 -> ' + a + '하다')
            return a + '하다'
        t = re.sub(a + r'합니다' + TAIL, f2, t)
    # ③ 「습니다」
    def f3(m):
        base = m.group(1)
        out = base + ('다' if base in ADJ_STEM else '는다')
        log.append(base + '습니다 -> ' + out)
        return out
    t = re.sub(r'([가-힣])습니다' + TAIL, f3, t)
    # ④ 「Xㅂ니다」 -> 「Xㄴ다」
    def f4(m):
        ch = m.group(1)
        j = _jamo(ch)
        if not j or j[2] != JONG_P:
            return m.group(0)
        out = _compose(j[0], j[1], JONG_N) + '다'
        log.append(ch + '니다 -> ' + out)
        return out
    t = re.sub(r'([가-힣])니다' + TAIL, f4, t)
    return t, log


def help_terse(t):
    """L1b — 도움말 **개조식 강화**. 초과가 남은 도움말에만 쓴다.

      `～이 가능하다` → `～ 가능`      -6B
      `가능하다`      → `가능`        -4B
      문미 `Xㄴ다`    → `Xㅁ`         -2B   (공격한다→공격함, 날려 버린다→날려 버림)
      `않는다`        → `않음`        -2B
    ★문미 `ㄴ다`→`ㅁ` 는 자모 계산이라 동사마다 표를 만들 필요가 없다.
    """
    t = re.sub(r'[이가] 가능하다' + TAIL, ' 가능', t)
    t = re.sub(r'가능하다' + TAIL, '가능', t)
    # ★`는다` 를 먼저 처리한다. 「는」에도 받침 ㄴ 이 있어서 아래 일반 규칙에 걸리면
    #   `뚫는다` 가 `뚫늠` 이 된다(실제로 그렇게 망가뜨렸다).
    t = re.sub(r'는다' + TAIL, '음', t)

    def f(m):
        ch = m.group(1)
        j = _jamo(ch)
        if not j or j[2] != JONG_N:
            return m.group(0)
        return _compose(j[0], j[1], JONG_M)
    return re.sub(r'([가-힣])다' + TAIL, f, t)


def trim_progressive(t, budget):
    """L2 — 대사에도 안전한 점진 축약. **맞을 때까지만** 깎는다.

      ① 쉼표 `，` 를 **뒤에서부터 하나씩**   -2B   (한국어는 없어도 읽힌다)
    ★한꺼번에 다 지우지 않는다 — 필요한 만큼만 깎아야 원문의 호흡이 덜 상한다.

    ★★말줄임표는 항상 **`・` 한 글자**로 쓴다(폰트가 그 한 칸 안에 점 3개를
      다 그린다 — `build_kr.py` 의 `DOT_ROWS`). `・・`/`・・・` 처럼 여러 칸을
      늘어놓지 않는다 — 이미 한 칸이 「전부」라 더 줄일 여지가 없다. 예전엔
      여기서 `・・・`→`・・`→`・` 로 한 칸씩 깎는 예산 지렛대가 있었는데,
      이제 그 세 형태가 전부 같은 걸 가리키므로 **삭제**한다. 새로 쓰는
      대사·번역문에도 처음부터 `・` 하나만 쓸 것 — 여러 개 쓰면 다음
      세션에서 또 일괄 치환해야 한다.
    """
    # ★쉼표를 통째로 지우면 `따위，긴` 이 `따위긴` 으로 **낱말이 붙는다.**
    #   뒤에 이미 공백이 없으면 **반각 공백(1B)** 으로 바꿔 경계를 남긴다(-1B).
    while size(t) > budget and '，' in t:
        i = t.rfind('，')
        nxt = t[i + 1:i + 2]
        rep = '' if (nxt in ('', ' ', '\n', '　') or nxt.startswith('%')) else ' '
        t = t[:i] + rep + t[i + 1:]
    return t


def rewrap(t, cap, nlines):
    """L4 핵심 — 본문을 **같은 줄 수 안에서 다시 조판**한다.

    ★원문의 개행 위치를 1:1 로 지키려 하면 한국어는 답이 없다 — 낱말 사이
      공백이 칸을 먹어서 같은 내용이 원문보다 길어지기 때문이다. 대신
      «줄 수 ≤ 원문 줄 수» 와 «줄마다 ≤ cap 글자» 두 조건만 지키고
      개행 위치는 새로 잡는다([[feedback_box_fit_two_conditions]]).
    ★앞뒤 제어토큰(`%z` … `%b`)은 그대로 보존한다. 본문 **중간**에 토큰이
      있으면(화자 이름표 등) 조판이 위험하므로 손대지 않고 None 을 돌린다.
    -> 새 문자열, 또는 불가능하면 None
    """
    m = re.match(r'^((?:%[A-Za-z][0-9]*)*)', t)
    prefix = m.group(1)
    rest = t[len(prefix):]
    m2 = re.search(r'((?:%[A-Za-z][0-9]*)*)$', rest)
    suffix = m2.group(1)
    body = rest[:len(rest) - len(suffix)] if suffix else rest
    if re.search(r'%[A-Za-z][0-9]*', body):
        return None                      # 본문 중간 토큰 — 건드리지 않는다
    words = [w for w in body.replace('\n', ' ').split(' ') if w]
    if not words:
        return None
    lines, cur = [], ''
    for w in words:
        cand = w if not cur else cur + ' ' + w
        if len(cand) <= cap:
            cur = cand
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    if any(len(l) > cap for l in lines) or len(lines) > nlines:
        return None
    return prefix + '\n'.join(lines) + suffix


