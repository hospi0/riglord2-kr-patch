def _euro(t, budget):
    """`X에 의해` → `X로 / X으로` — **받침 유무로 조사를 고른다**.
    ⛔무조건 `로` 로 바꾸면 「힘에 의해」가 「힘로」가 된다(실제 발생)."""
    while size(t) > budget:
        i = t.rfind('에 의해')
        if i <= 0:
            break
        prev = t[i - 1]
        if not ('가' <= prev <= '힣'):
            break
        jong = (ord(prev) - 0xAC00) % 28
        t = t[:i] + ('로' if jong == 0 else '으로') + t[i + 4:]
    return t


def shrink(t, budget):
    """예산에 맞을 때까지만 깎는다."""
    t = _euro(t, budget)
    for pat, repl in ((DOT, ''), (COMMA_SP, ','), (DOT_SP, '.')):
        while size(t) > budget:
            n = _last(pat, repl, t)
            if n is None:
                break
            t = n
    for a, b in CONTRACT:
        pos = len(t)
        while size(t) > budget:
            i = t.rfind(a, 0, pos)
            if i < 0:
                break
            t = t[:i] + b + t[i + len(a):]
            pos = i
    return t


def main(write):
    # 원문 자리(오프셋) 실측
    spots = {}
    rows = {r[0]: r for r in load_list()}
    iso = Iso(TRACK1)
    for path, s, e, t in prf_corpus.texts():
        if t is None:
            continue
        _, lba, sz, _ = rows[path]
        raw = iso.read(lba, sz)[s:e]
        spots[hashlib.sha1(raw).hexdigest()[:10]] = (path, s, e - s, t)

    have = set()
    with io.open(os.path.join(WORK, 'trans', 'strings.tsv'), encoding='utf-8') as f:
        next(f)
        for line in f:
            have.add(line.split('\t', 1)[0])

    good, errors, dup = [], [], 0
    with io.open(SRC, encoding='utf-8') as f:
        next(f)
        for lineno, line in enumerate(f, 2):
            a = line.rstrip('\n').split('\t')
            if len(a) < 6:
                errors.append((lineno, '열 부족'))
                continue
            k, ko_raw = a[0], a[5]
            if not ko_raw.strip():
                errors.append((k, '빈 번역'))
                continue
            if k not in spots:
                errors.append((k, '원문 자리를 못 찾음(키 불일치)'))
                continue
            if k in have:
                dup += 1
                continue
            path, off, n, jp = spots[k]
            ko = REWRITE.get(k) or normalize(unesc(ko_raw))
            ko = shrink(ko, n)
            if JAMO.search(ko):
                errors.append((k, '낱자모 사용 — 빌드가 죽는다'))
                continue
            try:
                ''.join(c for c in ko if not ('가' <= c <= '힣')).encode('cp932')
            except UnicodeEncodeError as e:
                errors.append((k, 'cp932 인코딩 불가 %s' % e))
                continue
            b = size(ko)
            if b > n:
                errors.append((k, '예산 초과 %dB > %dB  %s' % (b, n, path)))
                continue
            good.append((k, path, off, n, jp, ko))

    print('프로필 %d개 병합대상 / 중복 %d / 오류 %d' % (len(good), dup, len(errors)))
    for k, why in errors[:40]:
        print('   %s  %s' % (k, why))
    if errors:
        print('★오류가 있어 아무것도 쓰지 않았다.')
        return
    if not write:
        print('[미리보기 — --write 로 기록]')
        return

    T = lambda x: os.path.join(WORK, 'trans', x)
    with io.open(T('strings.tsv'), 'a', encoding='utf-8', newline='') as fs, \
         io.open(T('refs.tsv'), 'a', encoding='utf-8', newline='') as fr, \
         io.open(T('ko_final.tsv'), 'a', encoding='utf-8', newline='') as f1, \
         io.open(T('ko_shrunk.tsv'), 'a', encoding='utf-8', newline='') as f2:
        for k, path, off, n, jp, ko in good:
            fs.write('%s\t1\t%d\t%d\t\t%s\t\n' % (k, n, len(jp), esc(jp)))
            fr.write('%s\t%s\t%d\t%d\n' % (k, path, off, n))
            f1.write('%s\t%s\n' % (k, esc(ko)))
            f2.write('%s\t%s\n' % (k, esc(ko)))
    print('병합 완료: %d개 등록' % len(good))


if __name__ == '__main__':
    main('--write' in sys.argv)
