def unesc(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s):
            out.append({'n': '\n', 'r': '\r', 't': '\t', '\\': '\\'}.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return ''.join(out)


def esc(s):
    return (s.replace('\\', '\\\\').replace('\r', '\\r')
             .replace('\n', '\\n').replace('\t', '\\t'))


def size(t):
    n = 0
    for ch in t:
        n += 2 if '가' <= ch <= '힣' else len(ch.encode('cp932', 'replace'))
    return n


def normalize(t):
    t = t.replace('\u00b7', '\u30fb')            # · -> ・ (빌드 파괴 문자)
    t = t.replace('?', '？').replace('(', '（').replace(')', '）')
    # ★게임이 **스스로 자동 줄바꿈**한다. 일본어 원문은 낱말 사이 공백이 없어 줄이
    #   꽉 찼지만, 한국어는 공백이 끊는 자리라 «공백 없이 붙은 긴 덩어리»가 통째로
    #   다음 줄로 밀려 앞줄이 텅 빈다(실기: 「구석도」만 남고 「있지만（「조금？」」이 넘어감).
    #   여는 괄호 앞에 끊을 자리를 만들어 준다. 뒤 공백은 도로 거둬 바이트는 그대로.
    t = re.sub(r'(?<=[가-힣])（', ' （', t)
    t = re.sub(r'」 (?=[-－〜])', '」', t)
    # 반각 큰따옴표를 여는/닫는 짝으로 전각 낫표에
    out, open_q = [], True
    for ch in t:
        if ch == '"':
            out.append('「' if open_q else '」')
            open_q = not open_q
        else:
            out.append(ch)
    return ''.join(out)


