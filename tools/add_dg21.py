def esc(s):
    return s.replace('\\', '\\\\').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')


def main():
    rows = [r for r in load_list() if not r[3] and not r[0].endswith('/')]
    iso = Iso(TRACK1)

    want = set(TRANS)
    hits = {}
    for path, lba, size, oob in rows:
        if not path.upper().endswith(('.MAP', '.MSG', '.MAT')):
            continue
        d = iso.read(lba, size)
        for off, raw, t in strings(d):
            if t in want:
                hits.setdefault(t, []).append((path, off, raw))

    missing = want - set(hits)
    if missing:
        sys.exit('★디스크에서 못 찾은 원문 %d개: %s' % (len(missing), list(missing)[:3]))

    sp = os.path.join(WORK, 'trans', 'strings.tsv')
    rp = os.path.join(WORK, 'trans', 'refs.tsv')
    kp = os.path.join(WORK, 'trans', 'ko_final.tsv')

    # ★strings.tsv/refs.tsv 는 export_tsv.py 가 전체 155개 파일을 이미 다 훑어
    #   뽑아 둔 것이라 이 50개도 **이미 들어 있다**(추출은 됨, 번역만 안 됨).
    #   빠진 건 ko_final.tsv 쪽 뿐 — 거기에만 채워 넣는다.
    strings_keys = set()
    with io.open(sp, encoding='utf-8') as f:
        next(f)
        for line in f:
            strings_keys.add(line.split('\t', 1)[0])
    ko_final_keys = set()
    with io.open(kp, encoding='utf-8') as f:
        next(f)
        for line in f:
            a = line.rstrip('\n').split('\t')
            if len(a) >= 2 and a[1]:
                ko_final_keys.add(a[0])

    new_ko_rows = []
    skipped_translated, skipped_unextracted = 0, 0
    for t, locs in hits.items():
        raw0 = locs[0][2]
        for _, _, raw in locs:
            if raw != raw0:
                sys.exit('★같은 t 인데 raw 가 다르다: %r' % t)
        key = hashlib.sha1(raw0).hexdigest()[:10]
        if key in ko_final_keys:
            skipped_translated += 1
            continue
        if key not in strings_keys:
            skipped_unextracted += 1
            print('  ★strings.tsv 에도 없다(진짜 미추출) -> refs 까지 새로 붙여야 함: %s %r' % (key, t))
            continue
        n = len(raw0)
        new_ko_rows.append((key, TRANS[t], t, n, len(locs)))

    if not new_ko_rows:
        print('추가할 신규 항목 없음 (이미 번역됨 %d / 미추출이라 스킵 %d)'
              % (skipped_translated, skipped_unextracted))
        return

    with io.open(kp, 'a', encoding='utf-8', newline='') as f:
        for key, ko, t, n, cnt in new_ko_rows:
            f.write('%s\t%s\n' % (key, esc(ko)))

    print('신규 %d개 ko_final.tsv 에 추가 (이미 번역됨 %d / 미추출 스킵 %d)'
          % (len(new_ko_rows), skipped_translated, skipped_unextracted))
    for key, ko, t, n, cnt in new_ko_rows:
        print('  %s %dB %d회  %r' % (key, n, cnt, ko[:30]))


if __name__ == '__main__':
    main()
