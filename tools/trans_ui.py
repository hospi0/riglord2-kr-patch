def main():
    sp = os.path.join(WORK, 'trans', 'ui_strings.tsv')
    rows = []
    with io.open(sp, encoding='utf-8') as f:
        header = next(f)
        for line in f:
            a = line.rstrip('\n').split('\t')
            rows.append(a)

    missing = [a[0] for a in rows if a[0] not in TRANS and a[0] not in EXCLUDE]
    extra = [k for k in TRANS if k not in {a[0] for a in rows}]
    if missing:
        print('★번역표에 없는 key %d개:' % len(missing))
        for k in missing[:30]:
            row = next(a for a in rows if a[0] == k)
            print('   %s %r' % (k, row[6]))
    if extra:
        print('★번역표에만 있고 원본엔 없는 key %d개: %s' % (len(extra), extra[:10]))

    n = 0
    with io.open(sp, 'w', encoding='utf-8', newline='') as f:
        f.write(header)
        for a in rows:
            if a[0] in EXCLUDE:
                continue
            a[7] = esc(TRANS.get(a[0], ''))
            if a[7]:
                n += 1
            f.write('\t'.join(a) + '\n')
    print('번역 %d / %d 채움 (제외 %d)' % (n, len(rows) - len(EXCLUDE), len(EXCLUDE)))


if __name__ == '__main__':
    main()
