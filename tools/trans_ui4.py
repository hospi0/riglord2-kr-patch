def size(t):
    n = 0
    for ch in t:
        n += 2 if '가' <= ch <= '힣' else len(ch.encode('cp932', 'replace'))
    return n


def main():
    import ui_missing
    uniq = ui_missing.main()
    print()
    by_text = {}
    for fn, off, key, n, t in uniq:
        by_text.setdefault(t, (key, n))

    missing = [t for t in by_text if t not in TRANS and t not in EXCLUDE]
    extra = [t for t in TRANS if t not in by_text]
    over = []
    for t, (key, n) in by_text.items():
        if t in TRANS and size(TRANS[t]) > n:
            over.append((t, TRANS[t], size(TRANS[t]), n))

    print('검출 %d개 / 번역표 %d개' % (len(by_text), len(TRANS)))
    if missing:
        print('★번역 안 된 것 %d개:' % len(missing))
        for t in missing:
            print('   %r  (%dB)' % (t, by_text[t][1]))
    if extra:
        print('★검출에 없는데 번역표에 있는 것 %d개: %s' % (len(extra), extra[:8]))
    if over:
        print('★예산 초과 %d건:' % len(over))
        for t, ko, s, n in over:
            print('   %r -> %r  %dB > %dB' % (t, ko, s, n))
    if not missing and not extra and not over:
        print('OK — 전부 번역, 예산 초과 0')


if __name__ == '__main__':
    main()
